extern alias ValoraWeb;

using System.Net;
using System.Reflection;
using System.Text.RegularExpressions;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.Testing;
using Xunit;
using NavigationCatalog = ValoraWeb::Valora.Web.Navigation.NavigationCatalog;
using WebProgram = ValoraWeb::Program;

namespace Valora.Tests;

[Trait("Category", "BffIntegration")]
public sealed class ZeroBrokenPagesAuditTests : IClassFixture<WebApplicationFactory<WebProgram>> {
    private readonly WebApplicationFactory<WebProgram> _factory;

    public ZeroBrokenPagesAuditTests(WebApplicationFactory<WebProgram> factory) {
        _factory = factory;
    }

    private static string WebRootPath => Path.GetFullPath(
        Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "..", "Valora.Web"));

    [Fact]
    public void Layout_Referenced_Css_Files_All_Physically_Exist_In_Wwwroot() {
        var layoutPath = Path.Combine(WebRootPath, "Views", "Shared", "_Layout.cshtml");
        Assert.True(File.Exists(layoutPath), $"_Layout.cshtml não encontrado: {layoutPath}");

        var html = File.ReadAllText(layoutPath);
        var matches = Regex.Matches(html, @"href=""(/css/[^""]+)""");
        Assert.NotEmpty(matches);

        var missingFiles = new List<string>();
        foreach (Match m in matches) {
            var relPath = m.Groups[1].Value.TrimStart('/').Replace('/', Path.DirectorySeparatorChar);
            // remove query string or asp-append-version if any
            var cleanPath = relPath.Split('?')[0];
            var fullPath = Path.Combine(WebRootPath, "wwwroot", cleanPath);
            if (!File.Exists(fullPath)) {
                missingFiles.Add(m.Groups[1].Value);
            }
        }

        Assert.Empty(missingFiles);
    }

    [Fact]
    public void Layout_Referenced_Js_Files_All_Physically_Exist_In_Wwwroot() {
        var layoutPath = Path.Combine(WebRootPath, "Views", "Shared", "_Layout.cshtml");
        Assert.True(File.Exists(layoutPath), $"_Layout.cshtml não encontrado: {layoutPath}");

        var html = File.ReadAllText(layoutPath);
        var matches = Regex.Matches(html, @"src=""(/[^""]+\.js(?:[^""]*)?)""");
        Assert.NotEmpty(matches);

        var missingFiles = new List<string>();
        foreach (Match m in matches) {
            var rawUrl = m.Groups[1].Value;
            // /web-config.js is dynamically generated by WebConfigController, not a static file
            if (rawUrl.StartsWith("/web-config.js", StringComparison.OrdinalIgnoreCase)) continue;

            var cleanUrl = rawUrl.Split('?')[0].TrimStart('/').Replace('/', Path.DirectorySeparatorChar);
            var fullPath = Path.Combine(WebRootPath, "wwwroot", cleanUrl);
            if (!File.Exists(fullPath)) {
                missingFiles.Add(rawUrl);
            }
        }

        Assert.Empty(missingFiles);
    }

    [Fact]
    public void NavigationCatalog_Destinations_All_Have_Corresponding_Controllers_And_Views() {
        var catalog = new NavigationCatalog();
        var assembly = typeof(WebProgram).Assembly;
        var missingControllers = new List<string>();
        var missingActions = new List<string>();

        foreach (var item in catalog.Sections.SelectMany(s => s.Items)) {
            var controllerName = $"{item.Destination.Controller}Controller";
            var controllerType = assembly.GetType($"Valora.Web.Controllers.{controllerName}");
            if (controllerType is null) {
                missingControllers.Add(controllerName);
                continue;
            }

            var actionMethod = controllerType.GetMethods(BindingFlags.Public | BindingFlags.Instance)
                .FirstOrDefault(m => m.Name.Equals(item.Destination.Action, StringComparison.OrdinalIgnoreCase));
            if (actionMethod is null) {
                missingActions.Add($"{controllerName}.{item.Destination.Action}");
            }
        }

        Assert.Empty(missingControllers);
        Assert.Empty(missingActions);
    }

    [Theory]
    [InlineData("/Account/Login")]
    [InlineData("/Account/ForgotPassword")]
    [InlineData("/sobre")]
    [InlineData("/metodologia")]
    [InlineData("/demonstracao")]
    [InlineData("/diagnostico-gratuito")]
    [InlineData("/Diagnostico/Comecar")]
    [InlineData("/termos")]
    [InlineData("/health/web")]
    public async Task PublicPages_Return_200_Success_Without_Exception(string url) {
        using var client = _factory.CreateClient(new WebApplicationFactoryClientOptions {
            AllowAutoRedirect = false,
            BaseAddress = new Uri("https://localhost")
        });

        using var response = await client.GetAsync(url);
        var content = await response.Content.ReadAsStringAsync();

        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        Assert.NotEmpty(content);
        Assert.DoesNotContain("System.Exception", content, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("StackTrace", content, StringComparison.OrdinalIgnoreCase);
    }

    [Theory]
    [InlineData("/Dashboard")]
    [InlineData("/Help")]
    [InlineData("/AdminValora")]
    [InlineData("/ActionCenter/Plans")]
    [InlineData("/Results")]
    [InlineData("/Surveys")]
    [InlineData("/Reports")]
    [InlineData("/Evolution")]
    public async Task ProtectedPages_Redirect_Unauthenticated_Users_To_Login_Without_500_Crash(string url) {
        using var client = _factory.CreateClient(new WebApplicationFactoryClientOptions {
            AllowAutoRedirect = false,
            BaseAddress = new Uri("https://localhost")
        });

        using var response = await client.GetAsync(url);
        Assert.True(response.StatusCode == HttpStatusCode.Redirect || response.StatusCode == HttpStatusCode.Found,
            $"Rota protegida {url} deveria redirecionar para Login, mas retornou {response.StatusCode}");

        var location = response.Headers.Location?.ToString();
        Assert.NotNull(location);
        Assert.Contains("/Account/Login", location, StringComparison.OrdinalIgnoreCase);
    }

    [Theory]
    [InlineData(400, HttpStatusCode.BadRequest)]
    [InlineData(401, HttpStatusCode.Unauthorized)]
    [InlineData(403, HttpStatusCode.Forbidden)]
    [InlineData(404, HttpStatusCode.NotFound)]
    [InlineData(500, HttpStatusCode.InternalServerError)]
    public async Task Error_Pages_Do_Not_Mask_Http_Status_And_Never_Expose_Internal_Traces(int code, HttpStatusCode expected) {
        using var client = _factory.CreateClient(new WebApplicationFactoryClientOptions {
            AllowAutoRedirect = false,
            BaseAddress = new Uri("https://localhost")
        });

        using var response = await client.GetAsync($"/error/{code}");
        var html = await response.Content.ReadAsStringAsync();

        Assert.Equal(expected, response.StatusCode);
        Assert.NotEmpty(html);
        Assert.DoesNotContain("StackTrace", html, StringComparison.OrdinalIgnoreCase);
        Assert.DoesNotContain("System.Exception", html, StringComparison.OrdinalIgnoreCase);
    }
}
